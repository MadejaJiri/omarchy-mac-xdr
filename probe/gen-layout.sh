#!/bin/bash
# Generate layout.h: struct offsets of the *running* appledrm, read from BTF.
# The probe patches driver structures in place, so it must never guess these.
set -euo pipefail

BTF=/sys/kernel/btf/appledrm
BASE=/sys/kernel/btf/vmlinux
SWAP=${XDR_SWAP_STRUCT:-dcp_swap_submit_req_v13_3}
SWAPREC=${XDR_SWAPREC_STRUCT:-dcp_swap_v13_3}
SURF=${XDR_SURF_STRUCT:-dcp_surface_v13_3}

[[ -r $BTF ]] || { echo "gen-layout: $BTF missing (is appledrm loaded?)" >&2; exit 1; }
command -v pahole >/dev/null || { echo "gen-layout: pahole not installed" >&2; exit 1; }

dump() { pahole --btf_base "$BASE" -C "$1" "$BTF"; }

# offset of member $2 in struct $1
off() {
  local v
  v=$(dump "$1" | sed -nE "s/^.*[ *]$2(\[[0-9]+\])*;[[:space:]]*\/\*[[:space:]]*([0-9]+)[[:space:]]+([0-9]+).*$/\2/p" | head -1)
  [[ -n $v ]] || { echo "gen-layout: no member $2 in struct $1" >&2; exit 1; }
  echo "$v"
}

size() {
  local v
  v=$(dump "$1" | sed -nE 's/^.*\/\* size: ([0-9]+),.*$/\1/p' | head -1)
  [[ -n $v ]] || { echo "gen-layout: no struct $1" >&2; exit 1; }
  echo "$v"
}

swap_off=$(off "$SWAP" swap)
surf_off=$(off "$SWAP" surf)

cat <<EOF
/* Generated by gen-layout.sh for $(uname -r) -- do not edit. */
#ifndef XDR_LAYOUT_H
#define XDR_LAYOUT_H

#define XDR_KERNEL_RELEASE	"$(uname -r)"
#define XDR_DCP_DEV_OFF		$(off apple_dcp dev)
#define XDR_METHOD_TAG_OFF	$(off dcp_method_entry tag)

#define XDR_REQ_SIZE		$(size "$SWAP")
#define XDR_SWAP_SURFACES	4
#define XDR_BL_UNK_OFF		$((swap_off + $(off "$SWAPREC" bl_unk)))
#define XDR_BL_VALUE_OFF	$((swap_off + $(off "$SWAPREC" bl_value)))
#define XDR_BL_POWER_OFF	$((swap_off + $(off "$SWAPREC" bl_power)))
#define XDR_SURF_OFF		$surf_off
#define XDR_SURF_STRIDE		$(size "$SURF")
#define XDR_SURF_XFER_OFF	$(off dcp_surface xfer_func)
#define XDR_SURF_CSPACE_OFF	$(off dcp_surface colorspace)
#define XDR_SURF_NULL_OFF	$(off "$SWAP" surf_null)

#endif
EOF
